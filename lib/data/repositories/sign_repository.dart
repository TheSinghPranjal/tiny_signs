  static SignCategory? categoryById(String id) {
    try {
      return categories.firstWhere((c) => c.id == id);
    } catch (_) {
      return null;
    }
  }

  static Sign? signById(String id) {
    try {
      return signs.firstWhere((s) => s.id == id);
    } catch (_) {
      return null;
    }
  }

  static List<Sign> signsForCategory(String categoryId) =>
      signs.where((s) => s.categoryId == categoryId).toList();

